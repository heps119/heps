import { 증여세계산기 } from './extract.mjs';
const results = [];
const check = (ok, msg) => { results.push(ok); console.log(ok ? '✅' : '❌', msg); };
const 억 = 100_000_000;
const 원 = (t) => Number(String(t ?? '').replace(/[^\d]/g, '') || 0);
const 한도 = (r) => 원(r['g-r-limit']);

// 배우자 증여재산공제: 2008-01-01 이후 6억, 2003~2007 3억, 2002 이전 5억 (상증법 §53①)
const 배우자 = (날짜) => 증여세계산기({ g_relation: '1', g_new: String(10 * 억), g_gift_date: 날짜 });
check(한도(배우자('2008-01-01')) === 6 * 억, '배우자공제 — 2008-01-01 증여는 6억');
check(한도(배우자('2007-12-31')) === 3 * 억, '배우자공제 — 2007-12-31 증여는 3억');
check(한도(배우자('2003-01-01')) === 3 * 억, '배우자공제 — 2003-01-01 증여는 3억');
check(한도(배우자('2002-12-31')) === 5 * 억, '배우자공제 — 2002-12-31 증여는 5억');
check(한도(배우자('2026-03-01')) === 6 * 억, '배우자공제 — 2026년 증여는 6억');

// 직계비속 5천만 / 미성년 2천만 — 2014-01-01 경계
const 자녀 = (날짜, 관계 = '2') => 증여세계산기({ g_relation: 관계, g_new: String(3 * 억), g_gift_date: 날짜 });
check(한도(자녀('2014-01-01')) === 5000_0000 && 한도(자녀('2013-12-31')) === 3000_0000, '성년 자녀공제 — 2014-01-01 5천만 / 2013-12-31 3천만');
check(한도(자녀('2014-01-01', '3')) === 2000_0000 && 한도(자녀('2013-12-31', '3')) === 1500_0000, '미성년 자녀공제 — 2014-01-01 2천만 / 2013-12-31 1천5백만');
// 기타친족 1천만 — 2016-01-01 경계
const 친족 = (날짜) => 증여세계산기({ g_relation: '4', g_new: String(3 * 억), g_gift_date: 날짜 });
check(한도(친족('2016-01-01')) === 1000_0000 && 한도(친족('2015-12-31')) === 500_0000, '기타친족공제 — 2016-01-01 1천만 / 2015-12-31 5백만');

// 신고세액공제율: ~2016 10%, 2017 7%, 2018 5%, 2019~ 3%
const 율 = (날짜) => 증여세계산기({ g_relation: '2', g_new: String(3 * 억), g_gift_date: 날짜 })['g-r-report-rate'];
check(율('2016-12-31') === '10%' && 율('2017-06-01') === '7%' && 율('2018-06-01') === '5%' && 율('2019-01-01') === '3%', '신고세액공제율 — 2016 10% / 2017 7% / 2018 5% / 2019~ 3%');

// 세대생략 할증: 30%, 미성년 수증자 + 증여재산가액 20억 초과 + 2016-01-01 이후 40%, 부모 사망이면 제외
const 할증 = (옵션) => 증여세계산기({ g_relation: '6', g_new: String(3 * 억), g_gift_date: '2026-03-01', ...옵션 })['g-r-surtax'];
check(/30%/.test(할증({})), '세대생략 할증 — 성년 손자녀 30%');
check(/40%/.test(할증({ g_relation: '7', g_new: String(21 * 억) })), '세대생략 할증 — 미성년 손자녀 20억 초과 2016 이후 40%');
check(/30%/.test(할증({ g_relation: '7', g_new: String(21 * 억), g_gift_date: '2015-12-31' })), '세대생략 할증 — 2015-12-31 증여는 40% 아닌 30%');
check(할증({ 'g_parent_dead:checked': true }) === undefined, '세대생략 할증 — 수증자의 부모가 사망했으면 할증 없음');

const 실패 = results.filter((x) => !x).length;
console.log(`\n총 ${results.length}건 중 실패 ${실패}건`);
if (실패) process.exit(1);
